        <p>Quando un utente collega volontariamente un account social, possono essere acquisiti:</p>
        <ul>
            <li>identificativi dell'account e del profilo;</li>
            <li>nome visualizzato, immagine del profilo e informazioni di base autorizzate;</li>
            <li>ambiti di autorizzazione concessi, stato della connessione e relative scadenze;</li>
            <li>token di accesso e di rinnovo, conservati in forma cifrata nell'applicazione;</li>
            <li>capacità di pubblicazione comunicate dalla piattaforma.</li>
        </ul>


        <p>
            Possono essere trattati testi, immagini, video, pianificazioni, impostazioni di visibilità,
            identificativi delle pubblicazioni, esiti, stati di elaborazione e messaggi di errore.
        </p>

        <h3>Dati tecnici</h3>
        <p>
            I sistemi possono registrare indirizzo IP, data e ora, tipo di richiesta, informazioni sul browser,
